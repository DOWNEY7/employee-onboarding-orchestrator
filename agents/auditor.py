"""
agents/auditor.py
─────────────────────────────────────────────────────────────────────────────
AuditorAgent — validates the finalised pack against the required-steps matrix,
producing an AuditReport with pass/fail status and a list of AuditFindings.

Gap detection logic:
  For each step in the required matrix, check if a checklist item with a
  matching title or step_number exists in the generated checklist. Missing
  Critical/High steps fail the audit; missing Medium/Low steps are flagged
  as warnings.

Graph nodes:
    auditor_node(state: OnboardingState) -> dict
    leaver_auditor_node(state: LeaverState) -> dict
"""

from __future__ import annotations

import json
import logging
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from models.state import (
    AuditFinding,
    AuditReport,
    AuditSeverity,
    LeaverState,
    OnboardingState,
    Priority,
)

logger = logging.getLogger(__name__)

_REPO_ROOT = Path(__file__).parent.parent
ONBOARDING_MATRIX_PATH = _REPO_ROOT / "checklists" / "onboarding_matrix.json"
LEAVER_MATRIX_PATH = _REPO_ROOT / "checklists" / "leaver_matrix.json"


# ── Helpers ────────────────────────────────────────────────────────────────────

def _load_matrix(path: Path) -> list[dict[str, Any]]:
    with open(path, encoding="utf-8") as fh:
        return json.load(fh).get("steps", [])


def _normalise_title(title: str) -> str:
    """Lower-case and strip punctuation for fuzzy matching."""
    import re
    return re.sub(r"[^a-z0-9\s]", "", title.lower()).strip()


def _find_in_checklist(required_title: str, checklist: list[dict]) -> bool:
    """
    Return True if the required_title is represented in the checklist.
    Matching is done on normalised titles (case-insensitive, ignores punctuation).
    Also checks the first 5 words of the title for partial matches.
    """
    norm_required = _normalise_title(required_title)
    required_words = set(norm_required.split()[:5])

    for item in checklist:
        norm_item = _normalise_title(item.get("title", ""))
        item_words = set(norm_item.split()[:5])

        # Exact normalised match
        if norm_required == norm_item:
            return True

        # Word overlap: ≥ 60% of required words found in item title
        if required_words and len(required_words & item_words) / len(required_words) >= 0.6:
            return True

    return False


def _priority_to_severity(priority: str) -> AuditSeverity:
    """Convert a matrix priority value to an audit finding severity."""
    mapping = {
        Priority.CRITICAL.value: AuditSeverity.CRITICAL,
        Priority.HIGH.value:     AuditSeverity.HIGH,
        Priority.MEDIUM.value:   AuditSeverity.MEDIUM,
        Priority.LOW.value:      AuditSeverity.INFO,
    }
    return mapping.get(priority, AuditSeverity.MEDIUM)


def _run_audit(
    required_matrix: list[dict],
    checklist: list[dict],
    scripts: dict[str, str],
    comms: dict[str, Any],
) -> AuditReport:
    """
    Core audit logic: compare required matrix steps against the generated checklist.
    Also verify scripts and comms artefacts are present.
    """
    findings: list[AuditFinding] = []
    audit_failed = False

    # ── 1. Checklist gap detection ─────────────────────────────────────────────
    for required_step in required_matrix:
        title = required_step.get("title", "")
        priority = required_step.get("priority", "Medium")
        system = required_step.get("system", "")

        if not _find_in_checklist(title, checklist):
            severity = _priority_to_severity(priority)

            if severity in (AuditSeverity.CRITICAL, AuditSeverity.HIGH):
                audit_failed = True

            findings.append(AuditFinding(
                severity=severity,
                step_title=title,
                reason=f"Required step '{title}' (system: {system}, priority: {priority}) "
                       f"is not present in the generated checklist.",
                recommendation=f"Add '{title}' to the checklist before finalising the pack.",
            ))
            logger.warning(
                "AuditorAgent: MISSING step [%s] '%s'", priority, title
            )

    # ── 2. Script artefact validation ─────────────────────────────────────────
    if not scripts:
        findings.append(AuditFinding(
            severity=AuditSeverity.HIGH,
            step_title="PowerShell scripts",
            reason="No PowerShell scripts were generated by the ProvisionerAgent.",
            recommendation="Ensure the ProvisionerAgent runs successfully before the audit.",
        ))
        audit_failed = True
    else:
        for script_name, content in scripts.items():
            if content.startswith("# ERROR"):
                findings.append(AuditFinding(
                    severity=AuditSeverity.HIGH,
                    step_title=f"Script: {script_name}",
                    reason=f"Script '{script_name}' failed to render — contains error marker.",
                    recommendation="Review the template and re-run the ProvisionerAgent.",
                ))
                audit_failed = True

    # ── 3. Comms artefact validation ──────────────────────────────────────────
    if not comms or not comms.get("welcome_email_subject"):
        findings.append(AuditFinding(
            severity=AuditSeverity.HIGH,
            step_title="Welcome email",
            reason="Welcome email was not drafted by the CommsAgent.",
            recommendation="Ensure the CommsAgent runs successfully before the audit.",
        ))
        audit_failed = True

    if not comms or not comms.get("day1_guide_markdown"):
        findings.append(AuditFinding(
            severity=AuditSeverity.MEDIUM,
            step_title="Day-1 guide",
            reason="Day-1 guide was not drafted by the CommsAgent.",
            recommendation="Re-run the CommsAgent to generate the Day-1 guide.",
        ))

    # ── 4. Build report ────────────────────────────────────────────────────────
    critical_findings = [f for f in findings if f.severity == AuditSeverity.CRITICAL.value]
    if critical_findings:
        audit_failed = True

    report = AuditReport(
        passed=not audit_failed,
        total_required=len(required_matrix),
        total_present=len(required_matrix) - sum(
            1 for f in findings
            if "Required step" in f.reason
        ),
        findings=findings,
        generated_at=datetime.now(timezone.utc),
        auditor_notes=(
            "✅ All required steps accounted for. Pack ready for delivery."
            if not findings
            else f"⚠️  {len(findings)} finding(s) detected. Review before delivery."
        ),
    )

    return report


# ── Graph Node Functions ───────────────────────────────────────────────────────

def auditor_node(state: OnboardingState) -> dict:
    """LangGraph node: AuditorAgent (onboarding)."""
    logger.info("AuditorAgent: starting audit of onboarding pack")

    required_matrix = _load_matrix(ONBOARDING_MATRIX_PATH)
    checklist = state.get("checklist", [])
    scripts = state.get("scripts", {})
    comms = state.get("comms", {})

    report = _run_audit(required_matrix, checklist, scripts, comms)

    logger.info(
        "AuditorAgent: audit complete — passed=%s findings=%d",
        report.passed,
        len(report.findings),
    )

    return {"audit_report": report.model_dump(mode="json"), "error": ""}


def leaver_auditor_node(state: LeaverState) -> dict:
    """LangGraph node: AuditorAgent (leaver)."""
    logger.info("AuditorAgent: starting audit of leaver pack")

    required_matrix = _load_matrix(LEAVER_MATRIX_PATH)
    checklist = state.get("checklist", [])
    scripts = state.get("scripts", {})
    comms = state.get("comms", {})

    # For leaver, comms check is a 'handover note' — mapped to welcome_email_subject
    report = _run_audit(required_matrix, checklist, scripts, comms)

    logger.info(
        "AuditorAgent (leaver): audit complete — passed=%s findings=%d",
        report.passed,
        len(report.findings),
    )

    return {"audit_report": report.model_dump(mode="json"), "error": ""}


class AuditorAgent:
    """Thin wrapper for direct invocation outside the graph (e.g., testing)."""

    def run_audit(
        self,
        required_matrix: list[dict],
        checklist: list[dict],
        scripts: dict[str, str] | None = None,
        comms: dict[str, Any] | None = None,
    ) -> AuditReport:
        """Run the audit directly and return an AuditReport object."""
        return _run_audit(required_matrix, checklist, scripts or {}, comms or {})

    def run_onboarding(self, state: OnboardingState) -> dict:
        return auditor_node(state)

    def run_leaver(self, state: LeaverState) -> dict:
        return leaver_auditor_node(state)
